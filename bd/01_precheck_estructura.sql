-- Ejecutar con F5 y comparar contra lo esperado (ver LEEME_DESPLIEGUE.md, seccion 2).

-- (a) Columnas que el codigo usa. Esperado: 7 de CAT_PLANTILLA_REPORTE, 3 de CAT_PLANTILLA_REPORTE_PARRAFO, 7 de CARTA_RESPONSIVA.
SELECT OWNER, TABLE_NAME, COLUMN_NAME
  FROM ALL_TAB_COLUMNS
 WHERE (TABLE_NAME = 'CAT_PLANTILLA_REPORTE'
        AND COLUMN_NAME IN ('FIRMADA','ID_LOGO','TITULO_REPORTE','NOMBRE_REPORTE','ID_ENTE_PUBLICO','ID_SUBTIPO_SERVICIO','CVE_ESTATUS'))
    OR (TABLE_NAME = 'CAT_PLANTILLA_REPORTE_PARRAFO'
        AND COLUMN_NAME IN ('ORDEN','PARRAFO','CVE_ESTATUS'))
    OR (TABLE_NAME = 'CARTA_RESPONSIVA'
        AND COLUMN_NAME IN ('FIRMADA','ID_LOGO','NOMBRE_IMAGEN','RUTA_IMAGEN','NOMBRE_REPORTE','TITULO_REPORTE','ID_PLANTILLA_REPORTE'))
 ORDER BY TABLE_NAME, OWNER, COLUMN_NAME;

-- (b) Secuencias. Esperado: las dos.
SELECT SEQUENCE_OWNER, SEQUENCE_NAME
  FROM ALL_SEQUENCES
 WHERE SEQUENCE_NAME IN ('SEQ_PLANTILLA_REPORTE','SEQ_PLANTILLA_REPORTE_PARRAFO');

-- (c) Plantillas actuales de Correos Electronicos > Personal (ente 21, subtipo 40).
-- Esperado ANTES del despliegue: exactamente 1 con FIRMADA = 'S' (autografa). La 'N' (e.firma) la crea el script 02 si no existe.
SELECT ID_PLANTILLA_REPORTE, FIRMADA, CVE_ESTATUS, TITULO_REPORTE, NOMBRE_REPORTE, ID_LOGO
  FROM CAT_PLANTILLA_REPORTE
 WHERE ID_ENTE_PUBLICO = 21 AND ID_SUBTIPO_SERVICIO = 40
 ORDER BY FIRMADA, ID_PLANTILLA_REPORTE;
