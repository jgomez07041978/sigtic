DECLARE
  contador number;
BEGIN

    FOR R IN (SELECT * FROM SERVICIOS_TIC WHERE ID_UNIDAD_ADMTVA_OPERA_SERVTIC IS NULL) LOOP
    
    SELECT count(1) into contador FROM SIGGET_SAC_CATALOGOS.CAT_UNIDADES_ADMINISTRATIVAS UA WHERE UA.ID_ENTE_PUBLICO=R.ID_ENTE_PUBLICO_OPERA_SERV_TIC AND UA.ID_ENTE_PUBLICO=UA.ID_UNIDAD_ADMINISTRATIVA AND UA.ID_UNIDAD_ADMINISTRATIVA_PADRE IS NULL;
    
    
    if contador=1 then
        UPDATE SERVICIOS_TIC SET ID_UNIDAD_ADMTVA_OPERA_SERVTIC=R.ID_ENTE_PUBLICO_OPERA_SERV_TIC WHERE ID_SERVICIO_TIC=r.ID_SERVICIO_TIC and ID_UNIDAD_ADMTVA_OPERA_SERVTIC is null;
    end if;    
        
    END LOOP;
    commit;

END;