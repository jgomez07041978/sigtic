SELECT 

ST.CODIGO_SISTEMA,
ST.DESC_SISTEMA,
TS.DESC_TIPO_SISTEMA,
EP1.DESC_ENTE_PUBLICO AS ENTE_PUBLICO_ADMINISTRA,
UA1.DESC_UNIDAD_ADMINISTRATIVA AS UNIDAD_ADMINISTRA,
EP2.DESC_ENTE_PUBLICO AS ENTE_PUBLICO_OPERA,
UA2.DESC_UNIDAD_ADMINISTRATIVA AS UNIDAD_OPERA,
ST.CVE_ESTATUS
FROM CAT_SISTEMAS ST
INNER JOIN CAT_TIPO_SISTEMAS TS ON TS.CVE_TIPO_SISTEMA = ST.CVE_TIPO_SISTEMA
INNER JOIN SAC_CAT_ENTES_PUBLICOS EP1 ON EP1.ID_ENTE_PUBLICO=ST.ID_ENTE_PUBLICO_ADMIN_SISTEMA
LEFT JOIN SAC_CAT_UNIDAD_ADMINISTRATIVA UA1 ON UA1.ID_UNIDAD_ADMINISTRATIVA=ST.ID_UNIDAD_ADMTVA_ADMIN_SISTEMA
INNER JOIN SAC_CAT_ENTES_PUBLICOS EP2 ON EP2.ID_ENTE_PUBLICO=ST.ID_ENTE_PUBLICO_OPERA_SISTEMA
LEFT JOIN SAC_CAT_UNIDAD_ADMINISTRATIVA UA2 ON UA2.ID_UNIDAD_ADMINISTRATIVA=ST.ID_UNIDAD_ADMTVA_OPERA_SISTEMA
WHERE ST.ID_ENTE_PUBLICO_ADMIN_SISTEMA=13 OR ST.ID_ENTE_PUBLICO_OPERA_SISTEMA=13