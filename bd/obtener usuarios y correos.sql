SELECT EP.CORREO_INSTITUCIONAL, USU.CURP_USUARIO, 
USU.NOMBRE_USUARIO || CASE WHEN USU.SEGUNDO_NOMBRE_USUARIO IS NULL THEN '' ELSE ' '|| USU.SEGUNDO_NOMBRE_USUARIO END || 
CASE WHEN USU.APELLIDO_PATERNO_USUARIO IS NULL THEN '' ELSE ' '|| USU.APELLIDO_PATERNO_USUARIO END ||
CASE WHEN USU.APELLIDO_MATERNO_USUARIO IS NULL THEN '' ELSE ' '|| USU.APELLIDO_MATERNO_USUARIO END 
AS NOMBRE_COMPLETO,
ENP.DESC_ENTE_PUBLICO,
UA.DESC_UNIDAD_ADMINISTRATIVA, 
EP.DESC_CARGO,
CAT.DESC_CATEGORIA_USUARIO
FROM CAT_USUARIO_ENTE_PUBLICO EP 
INNER JOIN CAT_USUARIOS USU ON USU.ID_USUARIO = EP.ID_USUARIO
INNER JOIN CAT_ENTES_PUBLICOS ENP ON ENP.ID_ENTE_PUBLICO = EP.ID_ENTE_PUBLICO
LEFT JOIN CAT_UNIDADES_ADMINISTRATIVAS UA ON UA.ID_UNIDAD_ADMINISTRATIVA = EP.ID_UNIDAD_ADMINISTRATIVA
LEFT JOIN CAT_CATEGORIAS_USUARIOS CAT ON CAT.ID_CATEGORIA_USUARIO = EP.ID_CATEGORIA_USUARIO
WHERE EP.ID_ENTE_PUBLICO=21 AND EP.CVE_ESTATUS='VIG' and USU.CVE_ESTATUS='VIG'