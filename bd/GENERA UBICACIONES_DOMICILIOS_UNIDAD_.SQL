SELECT ep.ID_ENTE_PUBLICO, ep.CVE_ENTE_PUBLICO, ep.DESC_ENTE_PUBLICO, 
UA.DESC_UNIDAD_ADMINISTRATIVA, UB.ID_UBICACION_UNIDAD_ADMTVA, UB.DESC_UBICACION_UNIDAD_ADMTVA,
SD.ID_DOMICILIO_ENTE_PUBLICO, SD.DESC_DOMICILIO_COMPLETO_EP,SD.LATITUD,SD.LONGITUD

FROM CAT_ENTES_PUBLICOS ep
INNER JOIN CAT_UNIDADES_ADMINISTRATIVAS UA ON UA.ID_ENTE_PUBLICO = ep.ID_ENTE_PUBLICO  AND UA.CVE_ESTATUS = 'VIG'
LEFT JOIN CAT_UBICACIONES_UNIDAD_ADMTVA UB ON UB.ID_UBICACION_UNIDAD_ADMTVA=UA.ID_UBICACION_UNIDAD_ADMTRATIVA AND UB.CVE_ESTATUS='VIG' 
LEFT JOIN SAC_CAT_DOMICILIO_ENTE_PUBLICO SD ON SD.ID_DOMICILIO_ENTE_PUBLICO = UB.ID_DOMICILIO_UNIDAD_ADMTVA
where ep.CVE_ESTATUS='VIG' AND EP.ID_ENTE_PUBLICO!=0


ORDER BY TO_NUMBER(EP.CVE_ENTE_PUBLICO), UA.ID_UNIDAD_ADMINISTRATIVA