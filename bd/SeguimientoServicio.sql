SELECT US.ID_SERVICIO_TIC as idServicioTic, 
CU.CURP_USUARIO as curp, 
CU.NOMBRE_USUARIO as nombre,
CU.SEGUNDO_NOMBRE_USUARIO as segundoNombre,
CU.APELLIDO_PATERNO_USUARIO as apellidoPaterno,
CU.APELLIDO_MATERNO_USUARIO as apellidoMaterno,
EP.ID_ENTE_PUBLICO as idEntePublico,
EP.CVE_ENTE_PUBLICO as cveEntePublico,
EP.DESC_ENTE_PUBLICO as nombreEntePublico,
UA.CVE_UNIDAD_ADMINISTRATIVA as cveUnidadAdministrativa,
UA.DESC_UNIDAD_ADMINISTRATIVA as nombreUnidadAdministrativa,
ST.ID_TIPO_SERVICIO_TIC as idTipoServicio,
ST.DESC_SERVICIO_TIC as tipoServicio,
SUB.ID_SUBTIPO_SERVICIO_TIC as idSubtipoServicio,
SUB.DESC_SUBTIPO_SERVICIO_TIC as subtipoServicio,
CE.ESTATUS_SERVICIO as estatusServicio
FROM USUARIOS_SERVICIOS_TIC US
INNER JOIN SERVICIOS_TIC ST ON ST.ID_SERVICIO_TIC=US.ID_SERVICIO_TIC
INNER JOIN SIGGET_SAC_CATALOGOS.CAT_USUARIOS CU ON CU.CURP_USUARIO=US.CURP_USUARIO_SERVICIO_TIC
INNER JOIN SIGGET_SAC_CATALOGOS.CAT_USUARIO_ENTE_PUBLICO UE ON UE.ID_USUARIO_ENTE_PUBLICO = US.ID_USUARIO_ENTE_PUBLICO
INNER JOIN SIGGET_SAC_CATALOGOS.CAT_ENTES_PUBLICOS EP ON EP.ID_ENTE_PUBLICO=ST.ID_ENTE_PUBLICO_ADM_SERV_TIC
INNER JOIN SIGGET_SAC_CATALOGOS.CAT_UNIDADES_ADMINISTRATIVAS UA ON UA.ID_ENTE_PUBLICO = EP.ID_ENTE_PUBLICO AND UA.ID_UNIDAD_ADMINISTRATIVA=ST.ID_UNIDAD_ADMTVA_ADM_SERV_TIC
INNER JOIN CAT_TIPO_SERVICIOS_TIC TS ON TS.ID_TIPO_SERVICIO_TIC = ST.ID_TIPO_SERVICIO_TIC
INNER JOIN CAT_SUBTIPO_SERVICIOS_TIC SUB ON SUB.ID_SUBTIPO_SERVICIO_TIC = ST.ID_SUBTIPO_SERVICIO_TIC
INNER JOIN CAT_ESTATUS_SERVICIO CE ON CE.ID_ESTATUS_SERVICIO = US.ID_ESTATUS_SERVICIO
WHERE
    EP.ID_ENTE_PUBLICO = 21
    AND US.CVE_ESTATUS_USUARIO_SERV_TIC=US.CVE_ESTATUS
    AND US.CVE_ESTATUS_USUARIO_SERV_TIC='VIG'
    AND US.ID_ESTATUS_SERVICIO IN (2,5)
    AND UA.ID_UNIDAD_ADMINISTRATIVA IN (2)


