SELECT EP.ID_ENTE_PUBLICO,EP.CVE_ENTE_PUBLICO, EP.DESC_ENTE_PUBLICO, UA.ID_UNIDAD_ADMINISTRATIVA, UA.DESC_UNIDAD_ADMINISTRATIVA, 
BN.ID_BIEN, BN.NUM_INVENTARIO, BN.DESCRIPCION_BIEN, BN.FECHA_ALTA, BN.COSTO, BN.FECHA_CORTE
FROM SAC_CAT_ENTES_PUBLICOS EP 
INNER JOIN SAC_CAT_UNIDAD_ADMINISTRATIVA UA ON UA.ID_ENTE_PUBLICO = EP.ID_ENTE_PUBLICO AND UA.CVE_ESTATUS = 'VIG'
LEFT JOIN BIENES BN ON BN.ID_UNIDAD_ADMINISTRATIVA = UA.ID_UNIDAD_ADMINISTRATIVA
WHERE EP.CVE_ESTATUS='VIG' AND EP.ID_ENTE_PUBLICO !=0 AND BN.CVE_ESTATUS='VIG'
ORDER BY TO_NUMBER(EP.CVE_ENTE_PUBLICO), UA.ID_UNIDAD_ADMINISTRATIVA