select st.ID_SERVICIO_TIC, st.CVE_SERVICIO_TIC, st.NOMBRE_SERVICIO_TIC,
st.DESC_SERVICIO_TIC_ABREVIADO, st.DESC_SERVICIO_TIC, st.ALCANCE_SERVICIO_TIC,
st.OBS_SERVICIO_TIC, es.DESC_ESTATUS_SERVICIO_TIC, ts.DESC_TIPO_SERVICIO_TIC,
sbt.DESC_SUBTIPO_SERVICIO_TIC, scp.CVE_ENTE_PUBLICO as CVE_ENTE_PUBLICO_ADMIN, scp.DESC_ENTE_PUBLICO AS DESC_ENTE_PUBLICO_ADMIN,
scp2.CVE_ENTE_PUBLICO as CVE_ENTE_PUBLICO_opera, scp2.DESC_ENTE_PUBLICO AS DESC_ENTE_PUBLICO_opera

 from SERVICIOS_TIC st 
 inner join CAT_ESTATUS_SERVICIOS_TIC es on es.CVE_ESTATUS_SERVICIO_TIC = st.CVE_ESTATUS_SERVICIO_TIC
 inner join CAT_TIPO_SERVICIOS_TIC ts on ts.ID_TIPO_SERVICIO_TIC = st.ID_TIPO_SERVICIO_TIC
 inner join CAT_SUBTIPO_SERVICIOS_TIC sbt on sbt.ID_TIPO_SERVICIO_TIC = ts.ID_TIPO_SERVICIO_TIC and sbt.ID_SUBTIPO_SERVICIO_TIC = st.ID_SUBTIPO_SERVICIO_TIC
 left join SAC_CAT_ENTES_PUBLICOS scp on scp.ID_ENTE_PUBLICO=st.ID_ENTE_PUBLICO_ADM_SERV_TIC
 left join SAC_CAT_ENTES_PUBLICOS scp2 on scp2.ID_ENTE_PUBLICO=st.ID_ENTE_PUBLICO_OPERA_SERV_TIC
 where st.ID_TIPO_SERVICIO_TIC in (4,5,6,12) and st.cve_estatus='VIG'
 order by ts.DESC_TIPO_SERVICIO_TIC, sbt.DESC_SUBTIPO_SERVICIO_TIC