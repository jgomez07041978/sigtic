SELECT UA.ID_UNIDAD_ADMINISTRATIVA,UA.ID_UNIDAD_ADMINISTRATIVA_PADRE, 
 EP.CVE_ENTE_PUBLICO, UA.CVE_UNIDAD_ADMINISTRATIVA, UA.DESC_UNIDAD_ADMINISTRATIVA_ABR, UA.DESC_UNIDAD_ADMINISTRATIVA, UA.ES_UNIDAD_ADMINISTRATIVA_PPTAL 
FROM CAT_UNIDADES_ADMINISTRATIVAS UA 
INNER JOIN cat_entes_publicos EP ON EP.ID_ENTE_PUBLICO = UA.ID_ENTE_PUBLICO
WHERE EP.CVE_ESTATUS='VIG' AND UA.CVE_ESTATUS='VIG' AND EP.CVE_ENTE_PUBLICO!='00'
START WITH    UA.ID_UNIDAD_ADMINISTRATIVA_PADRE  IS NULL
CONNECT BY PRIOR UA.ID_UNIDAD_ADMINISTRATIVA = UA.ID_UNIDAD_ADMINISTRATIVA_PADRE
ORDER BY TO_NUMBER(EP.CVE_ENTE_PUBLICO), UA.CVE_UNIDAD_ADMINISTRATIVA