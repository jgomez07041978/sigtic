select st.ID_SUBTIPO_SERVICIO_TIC,sb.ID_TIPO_SERVICIO_TIC,  sb.DESC_TIPO_SERVICIO_TIC, st.DESC_SUBTIPO_SERVICIO_TIC, st.CONTROL_INVENTARIO, st.CONTROL_IP, st.CONTROL_PUERTO from CAT_SUBTIPO_SERVICIOS_TIC st
inner join CAT_TIPO_SERVICIOS_TIC sb on sb.ID_TIPO_SERVICIO_TIC = st.ID_TIPO_SERVICIO_TIC
AND st.CVE_ESTATUS = sb.CVE_ESTATUS
AND st.CVE_ESTATUS='VIG' ORDER BY sb.DESC_TIPO_SERVICIO_TIC, st.DESC_SUBTIPO_SERVICIO_TIC
