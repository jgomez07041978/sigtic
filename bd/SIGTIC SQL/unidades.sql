SELECT UA.ID_UNIDAD_ADMINISTRATIVA,
       UA.ID_UNIDAD_ADMINISTRATIVA_PADRE,
       UA.ID_ENTE_PUBLICO,
       EP.CVE_ENTE_PUBLICO,
       EP.DESC_ENTE_PUBLICO,
       EP.DESC_ENTE_PUBLICO_ABREVIADA,
       EP.DESC_ENTE_PUBLICO_ABREVIADA2,
       UA.CVE_UNIDAD_ADMINISTRATIVA,
       UA.CVE_UNIDAD_ADMINISTRATIVAPADRE,
       UA.CVE_UNIDAD_ADMINISTRATIVA2,
       UA.CVE_UNIDAD_ADMINISTRATIVA3,
       UA.DESC_UNIDAD_ADMINISTRATIVA,
       UA.DESC_UNIDAD_ADMINISTRATIVA_ABR,
       UA.DESC_UNIDAD_ADMINISTRATIVA_AB2,
       UA.DESC_UNIDAD_ADMINISTRATIVA_PTO,
       UA.ES_UNIDAD_ADMINISTRATIVA_PPTAL,
       UA.CVE_TIPO_UNIDAD_ADMINISTRATIVA,
       UA.ID_NIVEL_UNIDADADMINISTRATIVA,
       UA.ID_UBICACION_UNIDAD_ADMTRATIVA,
       UA.ULTIMO_NIVEL_UNIDAD_ADMTVA,
       UA.NUM_NIVEL_UNIDAD_ADMTVA,
       UA.RUTA_ID_UNIDAD_ADMINISTRATIVA,
       UA.RUTA_CVE_UNIDAD_ADMINISTRATIVA,
       UA.RUTA_DESC_UNIDAD_ADMTVA,
       UA.RUTA_DESC_UNIDAD_ADMTVA_ABR,
       UA.RUTA_DESC_UNIDAD_ADMTVA_ABR2,
       UA.RUTA_CVE_TIPO_UNIDAD_ADMTVA,
       UA.DESC_UNIDAD_ADMINISTRATIVA_XN,
       UA.DESC_UNIDAD_ADMINISTRATIVA_XN2,
       UA.INICIA_ID_UNIDAD_ADMTVA_NIVEL1,
       UA.INICIA_ID_UNIDAD_ADMTVA_NIVEL2,
       UA.INICIA_ID_UNIDAD_ADMTVA_NIVEL3,
       UA.INICIA_ID_UNIDAD_ADMTVA_NIVEL4,
       UA.NUM_NIVEL_ORGANIGRAMA,
       UA.NUM_ORDEN_ORGANIGRAMA,
       UA.DESC_CARGO_UNIDAD_ADMTVA_ORG,
       UA.DESC_CATEGORIA_UNIDAD_ADMTVA_O,
       UA.NUM_TELEFONO_UNIDAD_ADMTVA,
       UA.NUM_EXTENSION_UNIDAD_ADMTVA,
       UA.CORREO_UNIDAD_ADMTVA,
       UA.RFC_TITULAR_UNIDAD_ADMTVA,
        UA.NOMBRE_USUARIO,
      UA.SEGUNDO_NOMBRE_USUARIO,
      UA.APELLIDO_PATERNO_USUARIO,
      UA.APELLIDO_MATERNO_USUARIO,
       UA.NUM_ORDEN_UNIDADADMINISTRATIVA,
       UA.ID_COLOR_UNIDAD_ADMINISTRATIVA,
       UA.ID_IMAGEN_UNIDADADMINISTRATIVA,
       UA.IP_PC_MTTO,
       UA.NOMBRE_PC_MTTO,
       UA.CVE_USUARIO_SO_MTTO,
       UA.CVE_USUARIO_MTTO,
       UA.NOMBRE_APLICACION_MTTO,
       UA.FECHA_REGISTRO,
       UA.FECHA_ULTIMO_CAMBIO,
       UA.CVE_ESTATUS,
       ROWNUM NUM_ORDEN_UNIDADADMINISTRATIV2
  FROM (           
            SELECT CUA.ID_UNIDAD_ADMINISTRATIVA,
                              CUA.ID_UNIDAD_ADMINISTRATIVA_PADRE,
                              CUA.ID_ENTE_PUBLICO,
                              CUA.CVE_UNIDAD_ADMINISTRATIVA,
                              CUA.CVE_UNIDAD_ADMINISTRATIVAPADRE,
                              CUA.CVE_UNIDAD_ADMINISTRATIVA2,
                              CUA.CVE_UNIDAD_ADMINISTRATIVA3,
                              CUA.DESC_UNIDAD_ADMINISTRATIVA,
                              CUA.DESC_UNIDAD_ADMINISTRATIVA_ABR,
                              CUA.DESC_UNIDAD_ADMINISTRATIVA_AB2,
                              CUA.DESC_UNIDAD_ADMINISTRATIVA_PTO,
                              CUA.ES_UNIDAD_ADMINISTRATIVA_PPTAL,
                              CUA.CVE_TIPO_UNIDAD_ADMINISTRATIVA,
                              CUA.ID_NIVEL_UNIDADADMINISTRATIVA,
                              CUA.ID_UBICACION_UNIDAD_ADMTRATIVA,
                              CUA.ULTIMO_NIVEL_UNIDAD_ADMTVA,
            /* Inicia campos definidos por el nivel de la Unidad Administrativa */
                              LEVEL NUM_NIVEL_UNIDAD_ADMTVA,
                              SYS_CONNECT_BY_PATH (CUA.ID_UNIDAD_ADMINISTRATIVA, '>')   RUTA_ID_UNIDAD_ADMINISTRATIVA,
                              SYS_CONNECT_BY_PATH (CUA.CVE_UNIDAD_ADMINISTRATIVA, '>')   RUTA_CVE_UNIDAD_ADMINISTRATIVA,
                              SYS_CONNECT_BY_PATH (DESC_UNIDAD_ADMINISTRATIVA, '>')     RUTA_DESC_UNIDAD_ADMTVA,
                              SYS_CONNECT_BY_PATH (DESC_UNIDAD_ADMINISTRATIVA_ABR, '>') RUTA_DESC_UNIDAD_ADMTVA_ABR,
                              SYS_CONNECT_BY_PATH (DESC_UNIDAD_ADMINISTRATIVA_AB2, '>') RUTA_DESC_UNIDAD_ADMTVA_ABR2,
                              SYS_CONNECT_BY_PATH (CVE_TIPO_UNIDAD_ADMINISTRATIVA, '>') RUTA_CVE_TIPO_UNIDAD_ADMTVA,
                              LPAD ('-', LEVEL * 2) || DESC_UNIDAD_ADMINISTRATIVA       DESC_UNIDAD_ADMINISTRATIVA_XN,
                              LPAD (LEVEL||'-', LEVEL * 2) || DESC_UNIDAD_ADMINISTRATIVA       DESC_UNIDAD_ADMINISTRATIVA_XN2,

                              INSTR( SYS_CONNECT_BY_PATH (CUA.ID_UNIDAD_ADMINISTRATIVA, '>')||'>','>',1,1)+1 INICIA_ID_UNIDAD_ADMTVA_NIVEL1,
                              INSTR( SYS_CONNECT_BY_PATH (CUA.ID_UNIDAD_ADMINISTRATIVA, '>')||'>','>',1,2)+1 INICIA_ID_UNIDAD_ADMTVA_NIVEL2,
                              INSTR( SYS_CONNECT_BY_PATH (CUA.ID_UNIDAD_ADMINISTRATIVA, '>')||'>','>',1,3)+1 INICIA_ID_UNIDAD_ADMTVA_NIVEL3,
                              INSTR( SYS_CONNECT_BY_PATH (CUA.ID_UNIDAD_ADMINISTRATIVA, '>')||'>','>',1,4)+1 INICIA_ID_UNIDAD_ADMTVA_NIVEL4,

            /* Finaliza campos definidos por el nivel de la Unidad Administrativa */
                              
                              CUA.NUM_NIVEL_ORGANIGRAMA,
                              CUA.NUM_ORDEN_ORGANIGRAMA,
                              CUA.DESC_CARGO_UNIDAD_ADMTVA_ORG,
                              CUA.DESC_CATEGORIA_UNIDAD_ADMTVA_O,
                              CUA.NUM_TELEFONO_UNIDAD_ADMTVA,
                              CUA.NUM_EXTENSION_UNIDAD_ADMTVA,
                              CUA.CORREO_UNIDAD_ADMTVA,
                              CUA.RFC_TITULAR_UNIDAD_ADMTVA,
                              usu.NOMBRE_USUARIO,
                              usu.SEGUNDO_NOMBRE_USUARIO,
                              usu.APELLIDO_PATERNO_USUARIO,
                              usu.APELLIDO_MATERNO_USUARIO,
                              CUA.NUM_ORDEN_UNIDADADMINISTRATIVA,
                              CUA.ID_COLOR_UNIDAD_ADMINISTRATIVA,
                              CUA.ID_IMAGEN_UNIDADADMINISTRATIVA,
                              CUA.IP_PC_MTTO,
                              CUA.NOMBRE_PC_MTTO,
                              CUA.CVE_USUARIO_SO_MTTO,
                              CUA.CVE_USUARIO_MTTO,
                              CUA.NOMBRE_APLICACION_MTTO,
                              CUA.FECHA_REGISTRO,
                              CUA.FECHA_ULTIMO_CAMBIO,
                              CUA.CVE_ESTATUS
                        FROM CAT_UNIDADES_ADMINISTRATIVAS CUA
                        left join cat_usuarios usu on usu.RFC_USUARIO=CUA.RFC_TITULAR_UNIDAD_ADMTVA and usu.CVE_ESTATUS='VIG'
                        WHERE CUA.CVE_ESTATUS='VIG'
                        START WITH CUA.ID_UNIDAD_ADMINISTRATIVA_PADRE IS NULL
                        CONNECT BY PRIOR CUA.ID_UNIDAD_ADMINISTRATIVA = CUA.ID_UNIDAD_ADMINISTRATIVA_PADRE
                        ORDER SIBLINGS BY CUA.NUM_ORDEN_UNIDADADMINISTRATIVA, CUA.ID_UNIDAD_ADMINISTRATIVA
) UA, CAT_ENTES_PUBLICOS EP
WHERE UA.ID_ENTE_PUBLICO = EP.ID_ENTE_PUBLICO
AND EP.CVE_ESTATUS='VIG'