SELECT US.SEG_USUARIO, US.ID_USUARIO,US.ID_USUARIO_ENTE_PUBLICO,UE.ID_USUARIO_ENTE_PUBLICO, US.SISTEMA,
CU.NOMBRE_USUARIO, CU.SEGUNDO_NOMBRE_USUARIO,CU.APELLIDO_PATERNO_USUARIO, CU.APELLIDO_MATERNO_USUARIO,
CU.CVE_ESTATUS, EP.ID_ENTE_PUBLICO, EP.CVE_ENTE_PUBLICO,EP.CVE_ENTE_PUBLICO2, EP.DESC_ENTE_PUBLICO,EP.CVE_ESTATUS AS ESTATUS_ENTE, UE.CVE_ESTATUS AS ESTATUS_USU_ENTE
FROM SEG_USUARIOS US
INNER JOIN SIGGET_SAC_CATALOGOS.CAT_USUARIOS CU ON CU.ID_USUARIO=US.ID_USUARIO
INNER JOIN SIGGET_SAC_CATALOGOS.CAT_USUARIO_ENTE_PUBLICO UE ON UE.ID_USUARIO=US.ID_USUARIO
INNER JOIN SIGGET_SAC_CATALOGOS.CAT_ENTES_PUBLICOS EP ON EP.ID_ENTE_PUBLICO = UE.ID_ENTE_PUBLICO  AND UE.ID_ENTE_PUBLICO=EP.ID_ENTE_PUBLICO
WHERE US.SISTEMA='SIGTIC' AND US.CVE_ESTATUS='VIG'
--AND EP.ID_ENTE_PUBLICO IN (16,21)
ORDER BY  US.SEG_USUARIO