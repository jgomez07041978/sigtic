SELECT TS.DESC_TIPO_SERVICIO_TIC,TS.DESC_TIPO_SERVICIO_TIC_ABREV, SB.DESC_SUBTIPO_SERVICIO_TIC, SB.DESC_SUBTIPO_SERVICIO_TIC_ABR
FROM 
CAT_TIPO_SERVICIOS_TIC TS
INNER JOIN CAT_SUBTIPO_SERVICIOS_TIC SB ON SB.ID_TIPO_SERVICIO_TIC = TS.ID_TIPO_SERVICIO_TIC
WHERE TS.CVE_ESTATUS='VIG' AND SB.CVE_ESTATUS='VIG'