SELECT ST.* FROM SERVICIOS_TIC ST  
            INNER JOIN USUARIOS_SERVICIOS_TIC US ON US.ID_SERVICIO_TIC=ST.ID_SERVICIO_TIC 
            WHERE US.ID_USUARIO_ENTE_PUBLICO=49866
            AND ST.CVE_ESTATUS='VIG'  
            AND ST.ID_SERVICIO_TIC NOT IN (SELECT CRD.ID_SERVICIO_TIC FROM CARTA_RESPOSIVA_DETALLE CRD 
            INNER JOIN CARTA_RESPONSIVA CR ON CR.ID_CARTA_RESPONSIVA = CRD.ID_CARTA_RESPONSIVA 
            WHERE CR.ID_USUARIO_ENTE_PUBLICO=49866 AND CRD.CVE_ESTATUS='VIG' 
            AND CR.CVE_ESTATUS=CRD.CVE_ESTATUS)  
            AND ST.ID_TIPO_SERVICIO_TIC=3 AND ST.ID_SUBTIPO_SERVICIO_TIC=40